// Reproduce the Python data-only Unicode table from the pinned TypeScript dependency.
// node scripts/generate-scratchpad-unicode15.mjs /path/to/@unicode/unicode-15.0.0 [--check]
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const dependency = process.argv[2];
if (!dependency) throw new Error("Pass the installed @unicode/unicode-15.0.0 directory");
const metadata = JSON.parse(await readFile(resolve(dependency, "package.json"), "utf8"));
if (metadata.name !== "@unicode/unicode-15.0.0" || metadata.version !== "2.0.7") {
  throw new Error("Expected @unicode/unicode-15.0.0 version 2.0.7");
}
const source = resolve(dependency, "General_Category/Unassigned/ranges.mjs");
const { default: ranges } = await import(pathToFileURL(source).href);
const digest = createHash("sha256").update(await readFile(source)).digest("hex");
let last = 0, points = 0;
for (const range of ranges) {
  if (range.begin < last || range.end <= range.begin || range.end > 0x110000) {
    throw new Error("Invalid or unordered Unicode range");
  }
  last = range.end;
  points += range.end - range.begin;
}
const lines = [
  '"""Unicode 15.0 unassigned ranges; end is exclusive.',
  "",
  "Generated by scripts/generate-scratchpad-unicode15.mjs.",
  "Source: @unicode/unicode-15.0.0 2.0.7, Mathias Bynens, MIT license.",
  `Source range-module SHA-256: ${digest}`,
  '"""',
  "",
  "# fmt: off",
  "UNASSIGNED_RANGES: tuple[tuple[int, int], ...] = (",
];
for (let index = 0; index < ranges.length; index += 4) {
  lines.push("    " + ranges.slice(index, index + 4).map(({ begin, end }) =>
    `(0x${begin.toString(16).toUpperCase()}, 0x${end.toString(16).toUpperCase()}),`).join(" "));
}
lines.push(")", "# fmt: on", "");
const output = new URL("../python/src/synadia_ai/agent_fabric/_scratchpad_native/unicode15.py", import.meta.url);
const content = lines.join("\n");
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("Unicode15 table differs");
} else await writeFile(output, content);
console.log(`Unicode15 unassigned table: ${ranges.length} ranges, ${points} code points`);
